// Tipos de dados
// No JavaScript, todo o que armazenarmos em variáveis tem um tipo. Esses tipos definem o que podemos fazer com os valores.

// Principais tipos de dados:
// String (textos)
// Number (números)
// Boolean (verdadeiro ou falso)
// Object (objetos, que agrupam informações)
// Array (listas de valores)
//  Null (valor vazio)
// Undefined (quando algo não foi definido)



// STRING (textos)
// \uma string é um texto, sempre escrito entre aspas ("" ou '')
let nome= "Jarvis";
let mensagem = 'Olá, mundo!';

console.log(nome);
console.log(mensagem);

let saudacao = "Olá, " + nome + "!";
console.log(saudacao); //Exibe "Olá, Jarvis"

// typeof
// O typeof serve para descobrir o tipo de um valor ou variável

let nomeDois = "Brayan - Não pode fone de ovido";
console.log(typeof nomeDois);

let soma = 10 + 5;
console.log(soma);

